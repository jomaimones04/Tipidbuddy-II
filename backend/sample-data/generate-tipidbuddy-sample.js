function stockFor(productN, storeN) {
  const seed = (productN * 17 + storeN * 31) % 40;
  if (seed === 0) return 0;
  if (seed <= 3) return seed;
  if (seed <= 8) return 4 + (seed % 3);
  return 8 + ((productN + storeN * 7) % 48);
}

function stockStatus(stock) {
  if (stock === 0) return 'Out of Stock';
  if (stock <= 5) return 'Low Stock';
  return 'In Stock';
}

