const storePriceDocs = [];
let priceSeq = 1;

for (const p of products) {
  for (const storeN of p.storeNs) {
    const store = storeByN[storeN];
    const jitter = ((p.n * 3 + storeN * 5) % 7) * 0.004 - 0.012;
    let price = roundPeso(p.basePrice * store.factor * (1 + jitter));
    if (p.basePrice <= 12) {
      price = roundPeso(Math.max(6, p.basePrice + (store.factor - 1) * 8 + jitter * 10));
    }
    const stock = stockFor(p.n, storeN);
    storePriceDocs.push({
      _id: asOid(oid(PRICE_PREFIX, priceSeq)),
      productId: asOid(oid(PRODUCT_PREFIX, p.n)),
      storeId: asOid(oid(STORE_PREFIX, storeN)),
      storeName: store.storeName,
      storeType: store.storeType,
      storeLocation: { city: store.city, barangay: store.barangay },
      price,
      currency: 'PHP',
      stock,
      stockStatus: stockStatus(stock),
      isAvailable: stock > 0,
      priceUpdatedAt: asDate('2026-09-08T09:15:00.000Z'),
      createdAt: asDate(createdAt),
    });
    priceSeq += 1;
  }
}

